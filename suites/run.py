"""Run one suite folder against aerie and write the operation-by-client result matrix.

Usage: python -I suites/run.py suites/datacenter/t1 [--harness reports/harness.json] [--out reports/datacenter-t1]
                               [--clients http,python-dc-9.2.4,java-dc-9.2.4]

Clients (all generated by clients/generate.sh):
  http           raw HTTP (stdlib), checks status codes, headers and bodies directly
  python-<spec>  the generated Python client; its strict pydantic models must accept every response
  java-<spec>    the generated Java client (okhttp-gson); its strict models must accept every response
  ts-<spec>      the generated TypeScript client (typescript-axios); typed at compile time only
  python-<contract>  the Python client generated from aerie's own released contract: validates each
                 response against the contract's response schemas
Output in --out: matrix.md, matrix.json and failures/<scenario>__<client>.json (request, response, diff).
Exit code 1 when any cell is not PASS.
"""
import argparse
