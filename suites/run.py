import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BUILD = ROOT / "clients" / "build"
RUNNERS = ROOT / "clients" / "runners"
MISSING = object()
NEGATIVE = {"not_allowed", "not_found", "invalid_cql"}
INVALID_TOKEN = "kbt_lab_not_a_real_token"
# Writes carry the XSRF header (contracts-v3, behaviour/common.md); harmless on reads and JSON writes.
XSRF = {"X-Atlassian-Token": "no-check"}


def get_path(doc, path):
    cur = doc
    for part in path.split("."):
        if isinstance(cur, list) and part.isdigit() and int(part) < len(cur):
            cur = cur[int(part)]
        elif isinstance(cur, dict) and part in cur:
            cur = cur[part]
        else:
            return MISSING
    return cur


def run_checks(doc, checks):
    """Return a list of human-readable mismatches; empty means every check passed."""
    diffs = []
    for kind, path, *args in checks:
        val = get_path(doc, path) if doc is not None else MISSING
        if kind == "exists":
            ok = val is not MISSING
        elif kind == "missing":
            ok = val is MISSING
        elif kind == "eq":
            ok = val == args[0]
        elif kind in ("len_le", "len_ge"):
            ok = isinstance(val, list) and (len(val) <= args[0] if kind == "len_le" else len(val) >= args[0])
        elif kind == "none_eq":
            ok = isinstance(val, list) and all(get_path(x, args[0]) != args[1] for x in val)
        else:
            raise ValueError(f"unknown check {kind}")
        if not ok:
            got = "<missing>" if val is MISSING else json.dumps(val)[:200]
            diffs.append(f"{kind} {path} {json.dumps(args)}: got {got}")
    return diffs


def subst(value, fixtures):
    if isinstance(value, str):
        return re.sub(r"\{(\w+)\}", lambda m: str(fixtures.get(m.group(1), m.group(0))), value)
    if isinstance(value, list):
        return [subst(v, fixtures) for v in value]
    if isinstance(value, dict):
        return {k: subst(v, fixtures) for k, v in value.items()}
    return value


def auth_header(cred):
    if "token" in cred:
        return "Bearer " + cred["token"]
    return "Basic " + base64.b64encode(f"{cred['user']}:{cred['password']}".encode()).decode()


def credential(handoff, who):
    """"admin"/"user"/"noaccess" are basic-auth users; "token:<name>" is a seeded personal access token
    sent as a bearer token; an unknown token name sends a token aerie never issued."""
    if who.startswith("token:"):
        return {"token": handoff.get("tokens", {}).get(who[6:], {}).get("token") or INVALID_TOKEN}
    return handoff["credentials"][who]


def resolve(spec, p):
    while isinstance(p, dict) and "$ref" in p:
        p = get_path(spec, p["$ref"].lstrip("#/").replace("/", "."))
    return p if isinstance(p, dict) else {}


def operation(spec, method, path_tmpl):
    """The spec's operation object for method + path, with path-level parameters merged and $refs resolved,
    plus "form": the multipart field schemas when the request body is multipart/form-data."""
    item, renames = spec.get("paths", {}).get(path_tmpl), {}
    if item is None:
        # The same path under other parameter names ({id} here, {contentId} in that spec): names map by position.
        shape = lambda t: re.sub(r"\{\w+\}", "{}", t)  # noqa: E731
        other = next((t for t in spec.get("paths", {}) if shape(t) == shape(path_tmpl)), None)
        if other is None:
            return None
        item = spec["paths"][other]
        renames = dict(zip(re.findall(r"\{(\w+)\}", path_tmpl), re.findall(r"\{(\w+)\}", other)))
    op = item.get(method.lower())
    if not op:
        return None
    params = {}
    for p in item.get("parameters", []) + op.get("parameters", []):
        p = resolve(spec, p)
        params[p.get("name")] = p
    media = resolve(spec, op.get("requestBody")).get("content", {})
    form = resolve(spec, (media.get("multipart/form-data") or {}).get("schema")).get("properties")
    return dict(op, parameters=list(params.values()), form=form, renames=renames)


def spec_values(op, job):
    """Path and query values under this spec's own parameter names, plus the XSRF header where the spec declares
    it as a parameter (aerie's contract does)."""
    values = {op["renames"].get(k, k): v for k, v in job["path_params"].items()}
    values.update(job["params"] or {})
    for p in op["parameters"]:
        if p.get("in") == "header" and p.get("name") in XSRF:
            values[p["name"]] = XSRF[p["name"]]
    return typed_params(op, values)


def form_values(op, form):
    """The scenario's multipart fields as this spec declares them. A file is {"__file__": name, "content",
    "type"}; it stays a file only where the spec declares binary, otherwise the client gets its text, which is
    all that spec's generated client can send. Fields the spec does not declare are not sent."""
    out = {}
    for k, v in (form or {}).items():
        decl = (op.get("form") or {}).get(k)
        if decl is None:
            continue
        item = decl.get("items", {}) if decl.get("type") == "array" else decl
        binary = item.get("format") == "binary"
        vals = [x if not isinstance(x, dict) or binary else x["content"] for x in (v if isinstance(v, list) else [v])]
        if item.get("type") == "boolean":
            vals = [x if isinstance(x, bool) else str(x).lower() == "true" for x in vals]
        out[k] = vals if decl.get("type") == "array" else vals[0]
    return out


def typed_params(op, values):
    """Each value in the type this spec version declares (string in 9.x, integer limit/start in 10.x+,
    array-typed spaceKey in 10.x+)."""
    types = {p.get("name"): (p.get("schema") or {}).get("type") for p in op["parameters"]}
    out = {}
    for k, v in values.items():
        t = types.get(k)
        if t == "integer":
            out[k] = int(v)
        elif t == "boolean":
            out[k] = v if isinstance(v, bool) else str(v).lower() == "true"
        elif t == "array":
            out[k] = v if isinstance(v, list) else [str(v)]
        else:
            out[k] = str(v)
    return out


def build_url(base, path_tmpl, path_params, params):
    path = re.sub(r"\{(\w+)\}", lambda m: urllib.parse.quote(str(path_params[m.group(1)]), safe=""), path_tmpl)
    query = urllib.parse.urlencode({k: str(v) for k, v in (params or {}).items()})
    return base + path + ("?" + query if query else "")


def multipart(form):
    """multipart/form-data for form fields; a {"__file__": ...} value is a file part with its file name."""
    boundary = "lab-" + uuid.uuid4().hex
    out = b""
    for k, v in form.items():
        for x in v if isinstance(v, list) else [v]:
            if isinstance(x, dict):
                head = (f'Content-Disposition: form-data; name="{k}"; filename="{x["__file__"]}"\r\n'
                        f'Content-Type: {x.get("type", "application/octet-stream")}')
                data = x["content"].encode()
            else:
                head = f'Content-Disposition: form-data; name="{k}"'
                data = (str(x).lower() if isinstance(x, bool) else str(x)).encode()
            out += f"--{boundary}\r\n{head}\r\n\r\n".encode() + data + b"\r\n"
    return out + f"--{boundary}--\r\n".encode(), "multipart/form-data; boundary=" + boundary


def http_call(base, cred, path_tmpl, path_params, params, method="GET", body=None, form=None):
    """Raw HTTP: a JSON body, or multipart form fields (files keep their file names), or neither."""
    url = build_url(base, path_tmpl, path_params, params)
    headers = {"Authorization": auth_header(cred), "Accept": "application/json", **XSRF}
    data = None
    if form:
        data, headers["Content-Type"] = multipart(form)
    elif body is not None:
        data, headers["Content-Type"] = json.dumps(body).encode(), "application/json"
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return url, r.status, dict(r.headers), r.read()
    except urllib.error.HTTPError as e:
        return url, e.code, dict(e.headers), e.read()


class HttpClient:
    name = "http"

    def __init__(self, base):
        self.base = base

    def call(self, job):
        url, status, headers, body = http_call(self.base, job["cred"], job["path_tmpl"], job["path_params"], job["params"],
                                               job["method"], job.get("body"), job.get("form"))
        return {"url": url, "status": status, "headers": headers, "body": body, "client_error": None}


def snake(name):
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower().replace("-", "_")


def load_spec(spec_id):
    return json.loads((BUILD / "specs" / f"{spec_id}.json").read_text(encoding="utf-8"))


class PythonClient:
    """Calls the operation through the generated client; a response its models reject is a failure."""

    def __init__(self, spec_id, base):
        self.name = f"python-{spec_id}"
        self.base = base
        pkg_dir = BUILD / "python" / spec_id
        if not pkg_dir.is_dir():
            raise FileNotFoundError(f"{pkg_dir} missing: run clients/generate.sh")
        sys.path.insert(0, str(pkg_dir))
        self.pkg = importlib.import_module("client_" + re.sub(r"[.-]", "_", spec_id))
        self.spec = load_spec(spec_id)
        self.apis = [getattr(self.pkg, n) for n in dir(self.pkg) if n.endswith("Api") and isinstance(getattr(self.pkg, n), type)]

    def method_for(self, op):
        want = op["operationId"].replace("_", "").lower()
        for api in self.apis:
            for attr in dir(api):
                if attr.replace("_", "").lower() == want:
                    return api, attr
        raise LookupError(f"operationId {op['operationId']} not found in generated client")

    def call(self, job):
        op = operation(self.spec, job["method"], job["path_tmpl"])
        if op is None:
            return None  # operation not in this spec version
        url = build_url(self.base, job["path_tmpl"], job["path_params"], job["params"])
        api_cls, attr = self.method_for(op)
        client = self.pkg.ApiClient(self.pkg.Configuration(host=self.base))
        # The pinned specs declare no per-operation security, so the client would send no credentials.
        client.set_default_header("Authorization", auth_header(job["cred"]))
        for k, v in XSRF.items():
            client.set_default_header(k, v)
        # Keep the raw answer, so a 2xx the models reject is recorded with its status and body.
        seen = {}
        deserialize = client.response_deserialize

        def keep(response_data, response_types_map=None):
            seen["r"] = response_data
            return deserialize(response_data=response_data, response_types_map=response_types_map)

        client.response_deserialize = keep
        kwargs = {snake(k): v for k, v in spec_values(op, job).items()}
        as_file = lambda x: (x["__file__"], x["content"].encode()) if isinstance(x, dict) else x  # noqa: E731
        for k, v in form_values(op, job.get("form")).items():
            kwargs[snake(k)] = [as_file(x) for x in v] if isinstance(v, list) else as_file(v)
        if job.get("body") is not None:
            # The generated method's one parameter that is neither a spec parameter nor a form field is the body.
            spec_names = {snake(p.get("name", "")) for p in op["parameters"]} | {snake(k) for k in op.get("form") or {}}
            free = [n for n in inspect.signature(getattr(api_cls, attr)).parameters
                    if n != "self" and not n.startswith("_") and n not in spec_names]
            if not free:
                return {"url": url, "status": None, "headers": {}, "body": b"",
                        "client_error": "the generated method takes no request body"}
            # Built by the model's own from_json: a oneOf wrapper (aerie's label body) made from a plain dict
            # serializes to nothing, so the request would go out without a body.
            ann = inspect.signature(getattr(api_cls, attr)).parameters[free[0]].annotation
            model = next((a for a in [ann, getattr(ann, "__origin__", None), *getattr(ann, "__args__", ())] if hasattr(a, "from_json")), None)
            kwargs[free[0]] = model.from_json(json.dumps(job["body"])) if model else job["body"]
        try:
            resp = getattr(api_cls(client), attr + "_with_http_info")(**kwargs, _request_timeout=30)
            return {"url": url, "status": resp.status_code, "headers": dict(resp.headers or {}), "body": resp.raw_data, "client_error": None}
        except self.pkg.ApiException as e:
            return {"url": url, "status": e.status, "headers": dict(e.headers or {}), "body": (e.body or "").encode() if isinstance(e.body, str) else (e.body or b""), "client_error": None}
        except Exception as e:  # model validation, unexpected kwargs, transport
            r = seen.get("r")
            return {"url": url, "status": r.status if r else None, "headers": dict(r.headers) if r else {},
                    "body": (r.data or b"") if r else b"", "client_error": f"{type(e).__name__}: {e}"[:2000]}


class BatchClient:
    """A generated Java or TypeScript client, driven by its runner in clients/runners/ for all calls at once."""

    def __init__(self, kind, spec_id, base):
        self.name, self.base = f"{kind}-{spec_id}", base
        self.spec = load_spec(spec_id)
        pkg = "client_" + re.sub(r"[.-]", "_", spec_id)
        if kind == "java":
            target = BUILD / "java" / spec_id / "target"
            jars = [j for j in target.glob("*.jar") if not j.name.endswith(("-sources.jar", "-javadoc.jar", "-tests.jar"))]
            if not jars or not (target / "lib").is_dir():
                raise FileNotFoundError(f"{target} has no built client: run clients/generate.sh")
            cp = os.pathsep.join([str(jars[0]), str(target / "lib" / "*")])
            self.cmd = ["java", "-cp", cp, str(RUNNERS / "JavaRunner.java"), base, f"aerie.lab.{pkg}.api", str(jars[0])]
        else:
            client_dir = BUILD / "typescript-axios" / spec_id
            if not (client_dir / "dist" / "index.js").is_file():
                raise FileNotFoundError(f"{client_dir}/dist missing: run clients/generate.sh")
            self.cmd = ["node", str(RUNNERS / "ts-runner.js"), str(client_dir), base]
        self.results = {}

    def prepare(self, jobs):
        calls = []
        for job in jobs:
            op = operation(self.spec, job["method"], job["path_tmpl"])
            if op is None:
                continue
            values = spec_values(op, job)
            values.update(form_values(op, job.get("form")))
            calls.append({"id": job["id"], "operationId": op["operationId"], "params": values, "body": job.get("body"),
                          "hasParams": bool(op["parameters"] or op.get("form") or op.get("requestBody")),
                          "specNames": [p.get("name") for p in op["parameters"]] + list(op.get("form") or {}),
                          "auth": auth_header(job["cred"]), "headers": XSRF})
        with tempfile.TemporaryDirectory() as tmp:
            calls_file, out_file = Path(tmp) / "calls.json", Path(tmp) / "out.json"
            calls_file.write_text(json.dumps(calls), encoding="utf-8")
            try:
                p = subprocess.run(self.cmd + [str(calls_file), str(out_file)], capture_output=True, text=True, timeout=1800)
                if p.returncode != 0 or not out_file.is_file():
                    raise RuntimeError(f"runner exit {p.returncode}: {(p.stderr or p.stdout)[-1500:]}")
                self.results = {r["id"]: r for r in json.loads(out_file.read_text(encoding="utf-8"))}
            except Exception as e:
                self.results = {c["id"]: {"status": None, "headers": {}, "body": "", "client_error": f"{type(e).__name__}: {e}"} for c in calls}

    def call(self, job):
        r = self.results.get(job["id"])
        if r is None:
            return None  # operation not in this spec version
        return {"url": build_url(self.base, job["path_tmpl"], job["path_params"], job["params"]), "status": r.get("status"),
                "headers": r.get("headers") or {}, "body": r.get("body") or "", "client_error": r.get("client_error")}


def make_client(name, base):
    if name == "http":
        return HttpClient(base)
    kind, _, spec_id = name.partition("-")
    if kind == "python":
        return PythonClient(spec_id, base)
    if kind in ("java", "ts"):
        return BatchClient(kind, spec_id, base)
    raise ValueError(f"unknown client {name}")


def evaluate(scn, res):
    diffs = []
    if res["client_error"]:
        diffs.append("client rejected the call or response: " + res["client_error"])
        return diffs
    expect = scn["expect"]
    if str(res["status"]) not in expect:
        diffs.append(f"status {res['status']}, expected one of {sorted(expect)}")
        return diffs
    checks = expect[str(res["status"])]
    if checks:
        try:
            doc = json.loads(res["body"] or b"null")
        except ValueError:
            diffs.append("body is not JSON")
            return diffs
        diffs += run_checks(doc, checks)
    return diffs


def lookup(base, cred, path, params, pick):
    try:
        _, status, _, body = http_call(base, cred, path, {}, params)
        return (get_path(json.loads(body), pick) if status == 200 else MISSING), status
    except Exception as e:
        return MISSING, type(e).__name__


def resolve_fixtures(suite, handoff, base):
    """Each fixture by its lookup on the compatible surface; failing that, by the aerie UUID from seeding,
    which the surface accepts in place of a content id and answers with the decimal id (contracts-v2,
    behaviour/common.md, Identifiers). If even that fails the UUID itself is used, so the calls still name
    the right object."""
    found, notes = dict(handoff.get("ids", {})), []
    admin = credential(handoff, suite.get("admin_as", "admin"))
    for name, how in suite.get("fixtures", {}).items():
        if name in found:
            continue
        val, status = lookup(base, admin, how["path"], how["params"], how["pick"])
        if val is not MISSING:
            found[name] = val
            continue
        uuid = get_path(handoff, f"ids.aerie.pages.{name}")
        if uuid is MISSING:
            found[name] = f"UNRESOLVED-{name}"
            notes.append(f"fixture {name} not resolved (lookup status {status}, no aerie id from seeding)")
            continue
        val, by_uuid = lookup(base, admin, "/rest/api/content/{id}".replace("{id}", uuid), {}, "id")
        found[name] = val if val is not MISSING else uuid
        notes.append(f"fixture {name}: lookup status {status}; " + (f"decimal id {val} read by aerie id" if val is not MISSING
                     else f"using aerie id {uuid} (read by it: status {by_uuid})"))
    return found, notes


def run_step(base, handoff, step, fx, admin_as="admin"):
    """One setup step as raw HTTP; saves values from its answer into fx. Returns None, or why it failed."""
    method, path_tmpl = step["op"].split(" ", 1)
    try:
        url, status, _, body = http_call(base, credential(handoff, step.get("as", admin_as)), path_tmpl,
                                         subst(step.get("path", {}), fx), subst(step.get("params", {}), fx), method,
                                         subst(step.get("body"), fx), subst(step.get("form"), fx))
    except Exception as e:
        return f"{step['op']}: {type(e).__name__}: {e}"
    if status not in step.get("ok", [200, 201, 202, 204]):
        return f"{step['op']} answered {status}: {body[:300].decode('utf-8', 'replace')}"
    doc = None
    for name, path in step.get("save", {}).items():
        if doc is None:
            try:
                doc = json.loads(body or b"null")
            except ValueError:
                return f"{step['op']} answered {status} without JSON"
        val = get_path(doc, path) if doc is not None else MISSING
        if val is MISSING:
            return f"{step['op']} answered {status} without {path}"
        fx[name] = val
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("suite")
    ap.add_argument("--harness", default="reports/harness.json")
    ap.add_argument("--out")
    ap.add_argument("--clients", help="comma-separated subset, default: http, then python-, java- and ts-<spec> for every "
                                      "spec in the suite, then python-<contract> for every contract")
    args = ap.parse_args()

    suite_dir = Path(args.suite)
    handoff = json.loads(Path(args.harness).read_text(encoding="utf-8"))
    base = handoff["base_url"].rstrip("/")
    if (suite_dir / "cases.py").is_file():
        # A flow suite: multi-step cases written in Python (suites/auth), run with raw HTTP.
        sys.path.insert(0, str(suite_dir))
        cases = importlib.import_module("cases")
        out = Path(args.out or f"reports/{cases.SUITE['surface']}-{cases.SUITE['tier']}")
        (out / "failures").mkdir(parents=True, exist_ok=True)
        fixtures, notes = resolve_fixtures(cases.SUITE, handoff, base)
        rows = cases.run(base, handoff, fixtures, out / "failures")
        return write_matrix(out, cases.SUITE, base, ["http"], rows, notes, {})
    suite = json.loads((suite_dir / "scenarios.json").read_text(encoding="utf-8"))
    out = Path(args.out or f"reports/{suite['surface']}-{suite['tier']}")
    (out / "failures").mkdir(parents=True, exist_ok=True)

    names = args.clients.split(",") if args.clients else (
        ["http"] + [f"{kind}-{s}" for kind in ("python", "java", "ts") for s in suite["specs"]]
        + [f"python-{c}" for c in suite.get("contracts", [])])
    clients, setup_errors = {}, {}
    for n in names:
        try:
            clients[n] = make_client(n, base)
        except Exception as e:
            setup_errors[n] = f"{type(e).__name__}: {e}"

    fixtures, notes = resolve_fixtures(suite, handoff, base)
    if not handoff.get("seeded"):
        notes.append("harness reports seeded=false: " + ", ".join(handoff.get("gaps", {})))

    # One job per scenario and client. A scenario's "setup" steps run first, once per client, as raw HTTP, so every
    # client writes to objects of its own; {cx} is the client's number, and each step's "save" adds fixtures.
    jobs, prepared = {n: [] for n in names}, {}
    for scn in suite["scenarios"]:
        method, path_tmpl = scn["op"].split(" ", 1)
        for cx, n in enumerate(names):
            fx, setup_error = dict(fixtures, cx=cx), None
            for step in scn.get("setup", []):
                setup_error = run_step(base, handoff, step, fx, suite.get("admin_as", "admin"))
                if setup_error:
                    break
            job = {"id": scn["id"], "method": method, "path_tmpl": path_tmpl, "cred": credential(handoff, scn["as"]),
                   "path_params": subst(scn.get("path", {}), fx), "params": subst(scn.get("params", {}), fx),
                   "body": subst(scn.get("body"), fx), "form": subst(scn.get("form"), fx),
                   "scn": dict(scn, expect=subst(scn["expect"], fx)), "setup_error": setup_error}
            prepared[(scn["id"], n)] = job
            if not setup_error:
                jobs[n].append(job)
    for n, c in clients.items():
        if isinstance(c, BatchClient):
            c.prepare(jobs[n])

    rows, cells_by = [], {}
    for scn in suite["scenarios"]:
        row = {"scenario": scn["id"], "op": scn["op"], "cells": {}}
        for n in names:
            job = prepared[(scn["id"], n)]
            scn_eval = job["scn"]
            if n in setup_errors:
                row["cells"][n] = "ERROR"
                continue
            if job["setup_error"]:
                # Nothing to call: the objects this client's call needs could not be made (that operation's own
                # scenario reports why).
                res = {"url": None, "status": None, "headers": {}, "body": b""}
                diffs, blocked = ["setup failed: " + job["setup_error"]], True
            else:
                try:
                    res = clients[n].call(job)
                except Exception as e:
                    res = {"url": build_url(base, job["path_tmpl"], job["path_params"], job["params"]), "status": None,
                           "headers": {}, "body": b"", "client_error": f"{type(e).__name__}: {e}"}
                if res is None:
                    row["cells"][n] = "N/A"
                    continue
                if res["status"] is None and res.get("client_error") and all(k.startswith("4") for k in scn_eval["expect"]):
                    # The client refused to send a request the scenario expects aerie to refuse: nothing to judge.
                    row["cells"][n] = "N/A"
                    (out / "failures" / f"{job['id']}__{n}.json").write_text(json.dumps({
                        "scenario": job["id"], "client": n, "na": "the client refuses to send this request",
                        "client_error": res["client_error"]}, indent=2), encoding="utf-8")
                    continue
                diffs = evaluate(scn_eval, res)
                # A refusal proves nothing while the matching success case fails (e.g. nothing seeded, every path 404).
                last = job["id"].rsplit(".", 1)[1]
                needs = scn_eval.get("needs") or (job["id"].rsplit(".", 1)[0] + ".success" if last in NEGATIVE else None)
                blocked = not diffs and needs and cells_by.get((needs, n)) != "PASS"
                if blocked:
                    diffs = [f"passes only vacuously: {needs} did not pass for {n}"]
            # ERROR only when no answer came back at all; an answer the client rejects is a FAIL with its status.
            row["cells"][n] = "PASS" if not diffs else "BLOCKED" if blocked else ("ERROR" if res["status"] is None else "FAIL")
            ruled = scn_eval.get("ruled") or {}
            if row["cells"][n] == "FAIL" and n in ruled.get("clients", []):
                # A known exception the spec room ruled on: kept with its answer, counted apart from failures.
                row["cells"][n] = "RULED"
                diffs = [f"ruled {ruled['question']}: {ruled['why']}"] + diffs
            cells_by[(job["id"], n)] = row["cells"][n]
            if diffs:
                body = res["body"].decode("utf-8", "replace") if isinstance(res["body"], bytes) else str(res["body"])
                (out / "failures" / f"{job['id']}__{n}.json").write_text(json.dumps({
                    "scenario": job["id"], "client": n, "as": scn_eval["as"],
                    "request": {"method": job["method"], "url": res["url"], "body": job["body"], "form": job["form"]},
                    "response": {"status": res["status"], "headers": res["headers"], "body": body[:20000]},
                    "expected": scn_eval["expect"], "diff": diffs,
                }, indent=2), encoding="utf-8")
        rows.append(row)

    return write_matrix(out, suite, base, names, rows, notes, setup_errors)


def write_matrix(out, suite, base, names, rows, notes, setup_errors):
    (out / "matrix.json").write_text(json.dumps({"base_url": base, "clients": names, "setup_errors": setup_errors,
                                                 "notes": notes, "rows": rows}, indent=2), encoding="utf-8")
    md = [f"# {suite['surface']} {suite['tier']} against {base}", ""]
    md += [f"- {n}" for n in notes + [f"{k}: {v}" for k, v in setup_errors.items()]]
    md += ["", "| Scenario | Operation | " + " | ".join(names) + " |", "|---|---|" + "---|" * len(names)]
    md += [f"| {r['scenario']} | `{r['op']}` | " + " | ".join(r["cells"][n] for n in names) + " |" for r in rows]
    cells = [c for r in rows for c in r["cells"].values()]
    summary = {k: cells.count(k) for k in ("PASS", "FAIL", "BLOCKED", "ERROR", "N/A", "RULED")}
    md += ["", "Totals: " + ", ".join(f"{k} {v}" for k, v in summary.items()),
           "", "BLOCKED: the refusal case answered as expected, but its success case failed, so it proves nothing yet; or its setup failed.",
           "RULED: the client rejects the answer, and a ruling in the contract release says it always will (the question is in the failure file).",
           "ERROR: no answer reached the client (transport or setup); a 2xx the client rejects is a FAIL.",
           "N/A: the operation is not in that spec version, or the case cannot be run yet (its note says why)."]
    (out / "matrix.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))
    return 0 if summary["FAIL"] == summary["BLOCKED"] == summary["ERROR"] == 0 else 1


